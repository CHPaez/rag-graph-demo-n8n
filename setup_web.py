# ----------------------------------------------------------------------------- config
def load_cfg():
    cfg, existing = dict(DEFAULTS), ENV_FILE.exists()
    if existing:
        for line in ENV_FILE.read_text().splitlines():
            if line and not line.startswith("#") and "=" in line:
                k, v = line.split("=", 1)
                if k in cfg:
                    cfg[k] = v
    for k, n in (("POSTGRES_PASSWORD", 12), ("NEO4J_PASSWORD", 12), ("N8N_ENCRYPTION_KEY", 24)):
        if cfg[k] == "" or cfg[k].startswith("change_me"):
            cfg[k] = secrets.token_hex(n)
    if cfg["OWNER_PASSWORD"].startswith("change_me") or (not existing and cfg["OWNER_PASSWORD"] == ""):
        cfg["OWNER_PASSWORD"] = new_admin_password()
    return cfg, existing


def new_admin_password():
    return "Demo" + secrets.token_hex(5) + "1"


def write_cfg(cfg):
    lines = ["# Generated by setup_web.py / setup.sh - edit with either, or by hand."]
    lines += [f"{k}={cfg[k]}" for k in KEYS]
    tmp = ENV_FILE.with_suffix(".tmp")
    tmp.write_text("\n".join(lines) + "\n")
    tmp.chmod(0o600)
    tmp.replace(ENV_FILE)


def hint(v):
    if not v:
        return ""
    return "********" if len(v) <= 8 else f"{v[:3]}...{v[-4:]}"


def provider_of(cfg):
    return cfg["AI_PROVIDER"] if cfg["AI_PROVIDER"] in ("openai", "gemini") else "openai"


def active_key(cfg):
    return cfg["GEMINI_API_KEY"] if provider_of(cfg) == "gemini" else cfg["OPENAI_API_KEY"]


def sh(cmd, input_text=None, timeout=120):
    try:
        p = subprocess.run(cmd, cwd=ROOT, input=input_text, capture_output=True, text=True, timeout=timeout)
    except FileNotFoundError:
        return 127, f"command not found: {cmd[0]}"
    except subprocess.TimeoutExpired:
        return 124, "timeout"
    return p.returncode, (p.stdout or "") + (p.stderr or "")


def docker_ok():
    return sh(["docker", "compose", "version"])[0] == 0


def deployed():
    # stdout only: Docker prints warnings on stderr when .env does not exist yet.
    try:
        p = subprocess.run(["docker", "compose", "ps", "-a", "-q", "db"], cwd=ROOT, capture_output=True,
                           text=True, timeout=30)
    except (FileNotFoundError, subprocess.TimeoutExpired):
        return False
    return p.returncode == 0 and p.stdout.strip() != ""


def http_json(url, payload=None, headers=None, timeout=20):
    data = json.dumps(payload).encode() if payload is not None else None
    req = urllib.request.Request(url, data=data, headers={"Content-Type": "application/json", **(headers or {})})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return r.status, json.loads(r.read() or b"{}")


