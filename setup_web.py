class Handler(BaseHTTPRequestHandler):
    server_version = "RagWizard"

    def log_message(self, *args):  # never log: bodies may carry secrets
        pass

    def _send(self, code, payload, ctype="application/json; charset=utf-8"):
        LAST_ACTIVITY[0] = time.time()
        body = payload.encode() if isinstance(payload, str) else json.dumps(payload).encode()
        self.send_response(code)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.send_header("X-Content-Type-Options", "nosniff")
        self.send_header("Content-Security-Policy", "default-src 'self' 'unsafe-inline'; connect-src 'self'")
        self.end_headers()
        self.wfile.write(body)

    def _host_ok(self):
        return self.headers.get("Host", "").split(":")[0] in ("127.0.0.1", "localhost")

    def _token_ok(self, supplied):
        return secrets.compare_digest(supplied or "", TOKEN)

    def do_GET(self):
        url = urllib.parse.urlparse(self.path)
        if not self._host_ok():
            return self._send(403, {"error": "forbidden"})
        if url.path == "/":
            t = urllib.parse.parse_qs(url.query).get("t", [""])[0]
            if not self._token_ok(t):
                return self._send(403, "Abrí la URL completa que imprimió la terminal (incluye ?t=...).",
                                  "text/plain; charset=utf-8")
            return self._send(200, PAGE, "text/html; charset=utf-8")
        if not self._token_ok(self.headers.get("X-Token")):
            return self._send(403, {"error": "forbidden"})
        if url.path == "/api/state":
            return self._send(200, get_state())
        if url.path == "/api/job":
            return self._send(200, {k: JOB[k] for k in ("running", "name", "log", "ok")})
        if url.path == "/api/checks":
            return self._send(200, {"checks": run_checks()})
        self._send(404, {"error": "not found"})

    def do_POST(self):
        if not self._host_ok() or not self._token_ok(self.headers.get("X-Token")):
            return self._send(403, {"error": "forbidden"})
        try:
            n = int(self.headers.get("Content-Length", 0))
            body = json.loads(self.rfile.read(n) or b"{}")
        except Exception:
            return self._send(400, {"error": "bad request"})
        routes = {"/api/save": save_cfg, "/api/validate-key": validate_key, "/api/search": search,
                  "/api/deploy": lambda b: start_deploy(), "/api/ingest": lambda b: start_ingest()}
        fn = routes.get(urllib.parse.urlparse(self.path).path)
        if not fn:
            return self._send(404, {"error": "not found"})
        self._send(200, fn(body))


