def save_cfg(body):
    cfg, _ = load_cfg()
    errors, generated = [], None

    key = body.get("openai_api_key")
    if key is not None:
        if BAD_CHARS.search(key):
            errors.append("La API key no puede tener espacios, comillas, $, # ni barras invertidas.")
        else:
            cfg["OPENAI_API_KEY"] = key

    gkey = body.get("gemini_api_key")
    if gkey is not None:
        if BAD_CHARS.search(gkey):
            errors.append("La API key de Gemini no puede tener espacios, comillas, $, # ni barras invertidas.")
        else:
            cfg["GEMINI_API_KEY"] = gkey

    prov = body.get("ai_provider")
    if prov is not None:
        if prov not in ("openai", "gemini"):
            errors.append("Proveedor de IA no válido.")
        else:
            cfg["AI_PROVIDER"] = prov

    email = body.get("owner_email", cfg["OWNER_EMAIL"]).strip()
    if not EMAIL_RE.match(email):
        errors.append("El correo no es válido.")
    else:
        cfg["OWNER_EMAIL"] = email

    if body.get("owner_password_generate"):
        generated = new_admin_password()
        cfg["OWNER_PASSWORD"] = generated
    elif body.get("owner_password") is not None:
        pw = body["owner_password"]
        if pw == "":
            cfg["OWNER_PASSWORD"] = ""
        elif BAD_CHARS.search(pw):
            errors.append("La contraseña no puede tener espacios, comillas, $, # ni barras invertidas.")
        elif len(pw) < 8 or not re.search(r"\d", pw) or not re.search(r"[A-Z]", pw):
            errors.append("La contraseña necesita 8+ caracteres, un número y una mayúscula.")
        else:
            cfg["OWNER_PASSWORD"] = pw

    for field, k in (("owner_first_name", "OWNER_FIRST_NAME"), ("owner_last_name", "OWNER_LAST_NAME")):
        v = body.get(field, cfg[k]).strip()
        if not re.fullmatch(r"[\w.\-]+", v):
            errors.append("Nombre y apellido: una sola palabra, sin espacios ni símbolos.")
        else:
            cfg[k] = v

    port = str(body.get("port", cfg["N8N_PORT"])).strip()
    if not port.isdigit() or not 1024 <= int(port) <= 65535:
        errors.append("El puerto debe estar entre 1024 y 65535.")
    else:
        cfg["N8N_PORT"] = port

    tz = body.get("timezone", cfg["GENERIC_TIMEZONE"]).strip()
    if not tz or re.search(r"\s", tz):
        errors.append("La zona horaria no puede tener espacios (ejemplo: America/Bogota).")
    else:
        cfg["GENERIC_TIMEZONE"] = tz

    if errors:
        return {"ok": False, "errors": errors}
    write_cfg(cfg)
    return {"ok": True, "errors": [], "generated_password": generated}


def validate_key(body):
    cfg, _ = load_cfg()
    provider = body.get("ai_provider") or provider_of(cfg)
    stored = cfg["GEMINI_API_KEY"] if provider == "gemini" else cfg["OPENAI_API_KEY"]
    key = body.get("api_key") or stored
    if not key:
        return {"ok": False, "detail": "No hay ninguna API key para validar."}
    if provider == "gemini":
        req = urllib.request.Request(f"{GEMINI_BASE}/v1beta/models?pageSize=1", headers={"x-goog-api-key": key})
        name = "Google"
    else:
        req = urllib.request.Request(f"{OPENAI_BASE}/models", headers={"Authorization": f"Bearer {key}"})
        name = "OpenAI"
    try:
        with urllib.request.urlopen(req, timeout=15) as r:
            return {"ok": r.status == 200, "detail": f"La key es válida ({name} respondió 200)."}
    except urllib.error.HTTPError as e:
        if e.code in (400, 401, 403):
            return {"ok": False, "detail": f"{name} rechazó la key (HTTP {e.code}). Revisá que esté completa."}
        return {"ok": False, "detail": f"{name} respondió HTTP {e.code}."}
    except Exception as e:  # network errors
        return {"ok": False, "detail": f"No se pudo contactar a {name}: {e}"}


def run_job(name, steps):
    """steps: list of (label, argv). Streams output into JOB['log']."""
    def worker():
        ok = True
        for label, argv in steps:
            JOB["log"] += f"\n$ {label}\n"
            try:
                p = subprocess.Popen(argv, cwd=ROOT, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
            except FileNotFoundError:
                JOB["log"] += f"command not found: {argv[0]}\n"
                ok = False
                break
            for line in p.stdout:
                if "ExperimentalWarning" in line or "trace-warnings" in line:
                    continue
                JOB["log"] += line
            if p.wait() != 0:
                ok = False
                break
        JOB["ok"], JOB["running"] = ok, False

    with JOB_LOCK:
        if JOB["running"]:
            return False
        JOB.update(running=True, name=name, log="", ok=None)
    threading.Thread(target=worker, daemon=True).start()
    return True


def n8n_ready(port):
    # /healthz answers as soon as the HTTP server is up, before migrations and the owner
    # bootstrap finish; readiness + the REST settings route mean n8n is really usable.
    for path in ("/healthz/readiness", "/rest/settings"):
        try:
            with urllib.request.urlopen(f"http://127.0.0.1:{port}{path}", timeout=3) as r:
                if r.status != 200:
                    return False
        except Exception:
            return False
    return True


def wait_healthy(port, seconds=120):
    end = time.time() + seconds
    while time.time() < end:
        if n8n_ready(port):
            return True
        time.sleep(2)
    return False


def start_deploy():
    if not docker_ok():
        return {"ok": False, "error": "Docker Compose no está disponible en esta máquina."}
    cfg, _ = load_cfg()
    write_cfg(cfg)
    was_deployed = deployed()
    argv = ["docker", "compose", "up", "-d"] + (["--force-recreate", "n8n"] if was_deployed else [])

    def worker():
        ok = True
        JOB["log"] += "\n$ " + " ".join(argv) + "\n"
        p = subprocess.Popen(argv, cwd=ROOT, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
        for line in p.stdout:
            JOB["log"] += line
        if p.wait() != 0:
            ok = False
        else:
            JOB["log"] += f"\nEsperando a n8n en el puerto {cfg['N8N_PORT']} ...\n"
            ok = wait_healthy(cfg["N8N_PORT"])
            JOB["log"] += "n8n está listo.\n" if ok else "n8n no respondió en 120 s. Revisá: docker compose logs n8n\n"
        JOB["ok"], JOB["running"] = ok, False

    with JOB_LOCK:
        if JOB["running"]:
            return {"ok": False, "error": "Ya hay una tarea en curso."}
        JOB.update(running=True, name="deploy", log="", ok=None)
    threading.Thread(target=worker, daemon=True).start()
    return {"ok": True}


